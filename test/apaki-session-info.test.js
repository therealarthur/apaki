test('scanClaude: prompts as a pane counts them, replies once per API message, tool calls, compactions, models, tokens, names', async () => {
  const dir = tmp('si');
  try {
    const file = path.join(dir, `${SID}.jsonl`);
    fs.writeFileSync(file, transcript());
    const s = await scanClaude(file);
    assert.equal(s.prompts, 2, 'meta lines, command wrappers and tool results are not prompts');
    assert.equal(s.replies, 2, 'two API messages with words; the subagent line is not counted');
    assert.equal(s.toolCalls, 1);
    assert.equal(s.compactions, 1);
    assert.equal(s.model, 'claude-sonnet-4-5', 'the last reply\'s model, not the subagent\'s');
    assert.deepEqual(s.models, ['claude-opus-5-5', 'claude-sonnet-4-5']);
    assert.equal(s.created, Date.parse('2026-10-10T09:00:00Z'));
    assert.equal(s.lastActive, Date.parse('2026-10-10T10:02:00Z'), 'bookkeeping and subagent lines do not move it');
    assert.equal(s.version, '2.1.90');
    assert.equal(s.gitBranch, 'fix-checkout');
    assert.equal(s.cwd, 'C:\\acme\\web');
    assert.equal(s.customTitle, 'Fix the flaky checkout test');
    assert.equal(s.firstPrompt, 'Why does checkout fail one run in ten?');
    assert.deepEqual(s.tokens, { input: 13, output: 47, cacheRead: 100, cacheWrite: 0 });
    // A broken line is skipped, not fatal.
    fs.appendFileSync(file, '{"type":"user","timestamp":"2026-10-1\n');
    assert.equal((await scanClaude(file)).prompts, 2);
  } finally { fs.rmSync(dir, { recursive: true, force: true }); }
});

