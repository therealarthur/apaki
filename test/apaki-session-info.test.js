test('historyMarkdown: prompts and replies in order, tool calls as one line each, compactions marked, tool output left out', () => {
  const items = [
    { type: 'user', at: '2026-10-10T09:00:00Z', message: { content: 'Why does checkout fail?' } },
    { type: 'assistant', at: '2026-10-10T09:00:05Z', message: { content: [{ type: 'text', text: 'Let me look.' }, { type: 'tool_use', name: 'Bash', input: { command: 'npm test -- checkout' } }] } },
    { type: 'user', message: { content: [{ type: 'tool_result', tool_use_id: 't1', content: 'SECRET OUTPUT' }] } },
    { type: 'assistant', message: { content: [{ type: 'thinking', thinking: 'hidden' }, { type: 'text', text: 'The timer races.' }] } },
    { type: 'compact', summary: 'x' },
    { type: 'user', message: { content: [{ type: 'text', text: 'Fix it' }, { type: 'image_marker' }] } },
  ];
  const md = historyMarkdown(items, { id: SID, title: 'Fix the flaky checkout test', cwd: 'C:\\acme\\web', branch: 'main', now: Date.parse('2026-10-12T10:00:00Z') });
  assert.match(md, /^# Fix the flaky checkout test\n/);
  assert.match(md, new RegExp(`- Session: \`${SID}\``));
  assert.match(md, /- Folder: `C:\\acme\\web`/);
  assert.match(md, /## You \(2026-10-10 09:00:00 UTC\)\n\nWhy does checkout fail\?/);
  assert.match(md, /## Claude \(2026-10-10 09:00:05 UTC\)\n\nLet me look\.\n\n- Tool: \*\*Bash\*\* `npm test -- checkout`/);
  assert.equal((md.match(/## Claude/g) || []).length, 1, 'one heading for consecutive replies');
  assert.match(md, /The timer races\./);
  assert.match(md, /\*The conversation was compacted here\.\*/);
  assert.match(md, /Fix it\n\n\*1 image attached\*/);
  assert.equal(/SECRET OUTPUT|hidden/.test(md), false, 'tool output and thinking stay out');
  assert.equal(/\n{3,}/.test(md), false);
  assert.equal(md.includes(String.fromCharCode(0x2014)), false);
});

