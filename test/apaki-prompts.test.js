import test from 'node:test';
import assert from 'node:assert/strict';

import { buildHistory, isPromptItem, pageOf, promptList, promptOf, slimEntry } from '../apaki/engine/history.js';
import { turnsToMessages } from '../apaki/engine/codex-map.js';
import { CodexHistory } from '../apaki/engine/codex-history.js';

let n = 0;
const uid = () => `00000000-0000-4000-8000-${String(++n).padStart(12, '0')}`;
let clock = 0;
const at = () => new Date(Date.UTC(2026, 9, 12, 9, 0, clock++)).toISOString();

function T() {
  const lines = [];
  const add = (o) => { lines.push({ timestamp: at(), sessionId: 's', ...o }); return lines[lines.length - 1]; };
  return {
    lines,
    user: (parent, content, extra = {}) => add({ type: 'user', uuid: extra.uuid || uid(), parentUuid: parent?.uuid ?? null, message: { role: 'user', content }, ...extra }),
    asst: (parent, content, mid) => add({ type: 'assistant', uuid: uid(), parentUuid: parent?.uuid ?? null, message: { id: mid, role: 'assistant', model: 'claude-opus-5-5', content } }),
    att: (parent, attachment) => add({ type: 'attachment', uuid: uid(), parentUuid: parent?.uuid ?? null, attachment }),
    boundary: (logical) => add({ type: 'system', subtype: 'compact_boundary', uuid: uid(), parentUuid: null, logicalParentUuid: logical.uuid, compactMetadata: { trigger: 'manual', preTokens: 9000, postTokens: 900 } }),
    raw: (o) => add(o),
  };
}
const slim = (lines) => lines.map((j, i) => slimEntry(j, i * 10, 10)).filter(Boolean);
const build = (lines) => buildHistory(slim(lines).filter((e) => e.type !== 'queue-operation'), slim(lines).filter((e) => e.type === 'queue-operation'));
const say = (t, parent, text, mid) => t.asst(parent, [{ type: 'text', text }], mid);

/** A conversation with one of every kind of user line. */
function tricky() {
  const t = T();
  const u1 = t.user(null, 'first question');
  let a = say(t, u1, 'first answer', 'm1');
  const u2 = t.user(a, [{ type: 'image', source: { type: 'base64', media_type: 'image/png', data: 'AAAA' } }, { type: 'text', text: 'what is this' }]);
  const tu = t.asst(u2, [{ type: 'tool_use', id: 'tu1', name: 'Bash', input: { command: 'ls' } }], 'm2');
  const r1 = t.user(tu, [{ type: 'tool_result', tool_use_id: 'tu1', content: 'a.txt' }]);
  a = say(t, r1, 'a picture of a cat', 'm3');
  const u3 = t.user(a, '<system-reminder>Mind the rules.</system-reminder>\nthird question with a reminder first');
  a = say(t, u3, 'third answer', 'm4');
  const tn = t.user(a, '<task-notification><task-id>b1</task-id><status>completed</status></task-notification>');
  a = say(t, tn, 'the background task finished', 'm5');
  // A local command: the caveat, its record, its output. Not a prompt.
  const cav = t.user(a, '<local-command-caveat>Caveat: the messages below were generated by the user while running local commands.</local-command-caveat>', { isMeta: true });
  const rec = t.user(cav, '<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>');
  const out = t.user(rec, '<local-command-stdout>Set model to opus</local-command-stdout>');
  // A skill command Claude answers: a prompt, shown as typed.
  const skill = t.user(out, '<command-message>research is running…</command-message>\n<command-name>/research</command-name>\n<command-args>rust async</command-args>');
  const expanded = t.user(skill, [{ type: 'text', text: 'Research the topic: rust async' }], { isMeta: true });
  a = say(t, expanded, 'research results', 'm6');
  // A hook's words and an interruption: not prompts.
  const hook = t.user(a, '<user-prompt-submit-hook>remember to test</user-prompt-submit-hook>');
  const tu2 = t.asst(hook, [{ type: 'tool_use', id: 'tu2', name: 'Bash', input: { command: 'sleep 100' } }], 'm7');
  const intr = t.user(tu2, [{ type: 'tool_result', tool_use_id: 'tu2', content: '[Request interrupted by user for tool use]', is_error: true }]);
  const intr2 = t.user(intr, [{ type: 'text', text: '[Request interrupted by user for tool use]' }]);
  // A compaction and its summary.
  const b = t.boundary(intr2);
  const sum = t.user(b, 'This session is being continued from a previous conversation. Summary: ...', { isCompactSummary: true });
  // Bash mode: typed, but not for Claude.
  const bash = t.user(sum, '<bash-input>git status</bash-input>');
  const bashOut = t.user(bash, '<bash-stdout>clean</bash-stdout><bash-stderr></bash-stderr>');
  const u4 = t.user(bashOut, 'go');
  const tu3 = t.asst(u4, [{ type: 'tool_use', id: 'tu3', name: 'Read', input: { file_path: 'x' } }], 'm8');
  // A subagent's prompt (sidechain) and a message queued while Claude worked, which reached it.
  t.raw({ type: 'user', uuid: uid(), parentUuid: tu3.uuid, isSidechain: true, message: { role: 'user', content: 'subagent prompt' } });
  const meta = t.user(tu3, 'caveat text', { isMeta: true });
  const q = t.att(meta, { type: 'queued_command', prompt: 'also check the tests', source_uuid: uid() });
  const r3 = t.user(q, [{ type: 'tool_result', tool_use_id: 'tu3', content: 'file text' }]);
  a = say(t, r3, 'checked', 'm9');
  // The last prompt, written twice (a resume copies the line with the same uuid).
  const last = t.user(a, 'last question');
  t.lines.push({ ...last });
  say(t, last, 'last answer', 'm10');
  return t;
}

const PROMPTS = ['first question', 'what is this', 'third question with a reminder first', '/research rust async', 'go', 'also check the tests', 'last question'];

test('prompts: exactly what you typed is a prompt, everything else in a Claude transcript is not', () => {
  const h = build(tricky().lines);
  const list = promptList(h);
  assert.deepEqual(list.map((p) => p.text), PROMPTS);
  assert.equal(list[1].images, 1, 'the picture goes with its words');
  assert.ok(list.every((p) => p.id && p.at));
  // Every user item is marked, and only the marked ones count.
  const users = h.items.filter((it) => it.type === 'user');
  assert.ok(users.every((it) => it.prompt === false || (it.prompt && typeof it.prompt.text === 'string')));
  assert.equal(h.items.filter(isPromptItem).length, PROMPTS.length);
  // The interruption and bash mode are lines of their own, not your words.
  const notes = h.items.filter((it) => it.note).map((it) => it.note.text);
  assert.ok(notes.includes('Interrupted by you.'));
  assert.ok(notes.includes('! git status'));
  // The queued message keeps its mark (drawn as "steered in").
  assert.equal(h.items.find((it) => it.prompt && it.prompt.text === 'also check the tests').queued, true);
});

test('prompts: every page agrees with the whole list (before + the page\'s own = the next page\'s before)', () => {
  const h = build(tricky().lines);
  const total = promptList(h).length;
  for (const limit of [1, 2, 3, 5, 8, 400]) {
    let page = pageOf(h, { limit });
    let seenAfter = 0;
    for (;;) {
      const own = page.messages.filter(isPromptItem).length;
      assert.equal(page.prompts.total, total);
      assert.equal(page.prompts.before + own + seenAfter, total, `limit ${limit}`);
      seenAfter += own;
      if (!page.hasMore) { assert.equal(page.prompts.before, 0); break; }
      page = pageOf(h, { before: page.first, limit });
    }
    assert.equal(seenAfter, total);
  }
  // until: one page reaches back to a prompt that was not loaded yet, with a few messages before it.
  const first = promptList(h)[0];
  const newest = pageOf(h, { limit: 3 });
  const jump = pageOf(h, { before: newest.first, limit: 3, until: first.id });
  assert.ok(jump.messages.some((m) => m.uuid === first.id));
  assert.equal(jump.hasMore, false);
  assert.equal(jump.prompts.before, 0);
});

test('prompts: the rule on its own', () => {
  const u = (content, extra = {}) => ({ type: 'user', message: { content }, ...extra });
  assert.deepEqual(promptOf(u('hi')), { text: 'hi', images: 0 });
  assert.equal(promptOf(u('   ')), null);
  assert.equal(promptOf(u([{ type: 'tool_result', tool_use_id: 'x', content: 'y' }])), null);
  assert.deepEqual(promptOf(u([{ type: 'image_marker', ref: 'r' }])), { text: '', images: 1 });
  assert.equal(promptOf(u('hi', { parent_tool_use_id: 'toolu_1' })), null, 'a subagent\'s');
  assert.equal(promptOf(u('<command-name>/model</command-name><command-args></command-args>'), { localRun: true }), null);
  assert.deepEqual(promptOf(u('<command-name>review</command-name><command-args>main</command-args>')), { text: '/review main', images: 0 });
  assert.equal(promptOf(u('<local-command-stderr>x</local-command-stderr>')), null);
  assert.equal(promptOf(u('[Request interrupted by user]')), null);
  assert.equal(promptOf({ type: 'assistant', message: { content: 'x' } }), null);
  // A user message from the SDK's list (no mark): the same rule.
  assert.equal(isPromptItem(u('<system-reminder>x</system-reminder>\nreal words')), true);
  assert.equal(isPromptItem(u('<task-notification>x</task-notification>')), false);
});

/* ---------- Codex ---------- */

const turn = (id, items, extra = {}) => ({ id, status: 'completed', startedAt: 1760259600, items, ...extra });
const userItem = (id, text, images = 0) => ({ type: 'userMessage', id, content: [...(text ? [{ type: 'text', text }] : []), ...Array.from({ length: images }, () => ({ type: 'image', url: 'data:' }))] });
const agentItem = (id, text) => ({ type: 'agentMessage', id, text, phase: 'final_answer' });

test('prompts: Codex user messages are marked the same way (steered ones too), the rest are not', () => {
  const msgs = turnsToMessages([
    turn('t1', [userItem('u1', 'fix it'), { type: 'commandExecution', id: 'c1', command: 'ls', status: 'completed', aggregatedOutput: 'x', exitCode: 0 }, userItem('u2', 'also this'), agentItem('a1', 'done')]),
    turn('t2', [userItem('u3', '', 1), agentItem('a2', 'a cat')]),
    turn('t3', [{ type: 'contextCompaction', id: 'cc' }]),
  ]);
  const prompts = msgs.filter(isPromptItem);
  assert.deepEqual(prompts.map((m) => m.prompt.text), ['fix it', 'also this', '']);
  assert.equal(prompts[2].prompt.images, 1);
  assert.ok(msgs.filter((m) => m.type === 'user' && !isPromptItem(m)).every((m) => m.prompt === false), 'tool results are marked not a prompt');
});

/** A fake app-server's turns/list: newest first, `limit` per call, summary view = first user message and final answer. */
function fakeServer(turns) {
  const calls = [];
  const request = async (method, p) => {
    calls.push({ method, ...p });
    const all = turns.slice().reverse();
    const start = p.cursor ? Number(p.cursor) : 0;
    const data = all.slice(start, start + (p.limit || 10)).map((t) => (p.itemsView === 'summary' ? { ...t, items: [t.items.find((i) => i.type === 'userMessage'), t.items.filter((i) => i.type === 'agentMessage').pop()].filter(Boolean), itemsView: 'summary' } : t));
    const next = start + (p.limit || 10) < all.length ? String(start + (p.limit || 10)) : null;
    return { data, nextCursor: next };
  };
  return { request, calls };
}

test('prompts: a long Codex thread counts every prompt before the loaded pages, and the count gets exact as pages load', async () => {
  // 300 turns of a question and an answer, every 50th turn with a steered message too, and a few turns with no prompt.
  const turns = [];
  for (let i = 0; i < 300; i++) {
    const items = i % 97 === 5 ? [{ type: 'contextCompaction', id: `cc${i}` }] : [userItem(`u${i}`, `question ${i}`), ...(i % 50 === 0 ? [userItem(`s${i}`, `steer ${i}`)] : []), agentItem(`a${i}`, `answer ${i}`)];
    turns.push(turn(`t${String(i).padStart(3, '0')}`, items));
  }
  const truth = turnsToMessages(turns).filter(isPromptItem).length;
  const srv = fakeServer(turns);
  const hist = new CodexHistory({ request: srv.request });
  const first = await hist.firstPage('th', { limit: 40 });
  assert.equal(first.hasMore, true);
  // The count is read from the turn summaries (one request per 100 turns, no items loaded in full).
  const count = await hist.promptCount('th');
  assert.ok(srv.calls.filter((c) => c.itemsView === 'summary').every((c) => c.limit === 100));
  const own = first.messages.filter(isPromptItem).length;
  // Steered messages in turns not loaded yet are the only thing the summary cannot see.
  const loadedIds = new Set(first.messages.map((m) => m.uuid));
  const unloadedSteers = turns.flatMap((t) => t.items).filter((i) => i.type === 'userMessage' && i.id.startsWith('s') && !loadedIds.has(i.id)).length;
  assert.equal(count.before + own, truth - unloadedSteers);
  // Page after page up to the start: the last page says 0 before, and everything adds up to the truth.
  let page = first;
  let loaded = own;
  while (page.hasMore) {
    page = await hist.pageBefore('th', page.first, { limit: 40 });
    loaded += page.messages.filter(isPromptItem).length;
    assert.ok(page.prompts, 'every later page carries the count');
  }
  assert.equal(page.prompts.before, 0);
  assert.equal(loaded, truth);
  // The list of prompts: every turn's prompt from the summaries, the loaded turns' steered ones too, oldest first.
  const list = await hist.promptList('th');
  assert.equal(list.prompts.length, truth);
  assert.equal(list.prompts[0].text, 'question 0');
  assert.equal(list.prompts[1].text, 'steer 0');
  assert.equal(list.prompts.at(-1).text, 'question 299');
});

test('prompts: a Codex page asked to reach an older prompt loads every turn up to it', async () => {
  const turns = Array.from({ length: 120 }, (_, i) => turn(`t${i}`, [userItem(`u${i}`, `q${i}`), agentItem(`a${i}`, `a${i}`)]));
  const hist = new CodexHistory({ request: fakeServer(turns).request });
  const first = await hist.firstPage('th', { limit: 20 });
  const page = await hist.pageBefore('th', first.first, { limit: 20, until: 'u3' });
  assert.ok(page.messages.some((m) => m.uuid === 'u3'));
  assert.ok(!page.messages.some((m) => m.uuid === 'u2') || page.messages.findIndex((m) => m.uuid === 'u2') < page.messages.findIndex((m) => m.uuid === 'u3'));
});
